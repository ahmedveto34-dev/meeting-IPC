// Helper to ensure 'ما لم يتم إنجازه من الاجتماع السابق' is always at index 0 of agenda
export function ensurePreviousUnfinishedItemFirst(agenda: string[]): string[] {
  if (!Array.isArray(agenda) || agenda.length === 0) {
    return ["ما لم يتم إنجازه من الاجتماع السابق"];
  }
  const hasPrior = agenda.some((item) => typeof item === "string" && item.includes("ما لم يتم إنجازه"));
  if (hasPrior) {
    const withoutPrior = agenda.filter((item) => typeof item === "string" && !item.includes("ما لم يتم إنجازه"));
    const priorItem = agenda.find((item) => typeof item === "string" && item.includes("ما لم يتم إنجازه"))!;
    return [priorItem, ...withoutPrior];
  }
  return ["ما لم يتم إنجازه من الاجتماع السابق", ...agenda];
}

