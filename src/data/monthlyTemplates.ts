// Helper to normalize, validate, and sanitize uploaded templates from any external medical center
export function normalizeMonthlyTemplates(raw: any): MonthlyThemeTemplate[] {
  if (!raw) return DEFAULT_MONTHLY_TEMPLATES;

  let list: any[] = [];
  if (Array.isArray(raw)) {
    list = raw;
  } else if (raw && typeof raw === "object") {
    if (Array.isArray(raw.monthlyTemplates)) {
      list = raw.monthlyTemplates;
    } else if (Array.isArray(raw.templates)) {
      list = raw.templates;
    } else if (Array.isArray(raw.data)) {
      list = raw.data;
    } else if (Array.isArray(raw.months)) {
      list = raw.months;
    }
  }

  if (!list || list.length === 0) {
    return DEFAULT_MONTHLY_TEMPLATES;
  }

  return list.map((item: any, index: number) => {
    const monthIdx = typeof item.monthIndex === "number" ? item.monthIndex : index + 1;
    const defaultTemplate = DEFAULT_MONTHLY_TEMPLATES[index] || DEFAULT_MONTHLY_TEMPLATES[0];

    const rawAgenda = Array.isArray(item.agenda)
      ? item.agenda.filter((a: any) => typeof a === "string" && a.trim().length > 0)
      : defaultTemplate.agenda;

    const agenda = ensurePreviousUnfinishedItemFirst(rawAgenda);

    const defaultKpis = Array.isArray(item.defaultKpis) && item.defaultKpis.length > 0
      ? item.defaultKpis.map((k: any) => ({
          name: String(k.name || "مؤشر أداء"),
          value: String(k.value || "%85"),
          target: k.target ? String(k.target) : "%95",
        }))
      : defaultTemplate.defaultKpis;

    const sampleDecisions = Array.isArray(item.sampleDecisions) && item.sampleDecisions.length > 0
      ? item.sampleDecisions.map((d: any) => ({
          topic: String(d.topic || "ملاحظة ومتابعة"),
          decision: String(d.decision || "الإجراء التصحيحي المتخذ"),
          responsible: String(d.responsible || "مسؤول مكافحة العدوى"),
          duration: String(d.duration || "أسبوع"),
          monitoringMethod: String(d.monitoringMethod || "المرور والمراجعة"),
        }))
      : defaultTemplate.sampleDecisions;

    return {
      key: item.key || `month-${monthIdx}`,
      monthIndex: monthIdx,
      monthName: String(item.monthName || `شهر ${monthIdx} - ${item.category || "مكافحة العدوى"}`),
      themeTitle: String(item.themeTitle || item.title || defaultTemplate.themeTitle),
      category: String(item.category || defaultTemplate.category),
      focusSummary: String(item.focusSummary || item.description || defaultTemplate.focusSummary),
      agenda,
      defaultKpis,
      sampleDecisions,
    };
  });
}
