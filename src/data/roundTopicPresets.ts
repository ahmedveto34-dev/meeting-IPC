/**
 * دالة مساعدة لتحويل موضوع افتراضي إلى كائن تقرير مرور كامل
 */
export function createRoundReportFromTopicPreset(
  preset: RoundTopicPreset,
  context?: {
    centerName?: string;
    inspector?: string;
    day?: string;
    date?: string;
    period?: "صباحي" | "مسائي" | "ليلي";
  }
): RoundReport {
  const today = new Date();
  const dayNames = ["الأحد", "الاثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت"];
  const currentDay = context?.day || dayNames[today.getDay()] || "الأحد";
  const currentDate = context?.date || today.toISOString().split("T")[0].replace(/-/g, "/");

  return {
    id: `round-topic-${preset.id}-${Date.now()}`,
    title: `تقرير مرور ميداني - ${preset.topicTitle}`,
    department: preset.departmentScope,
    day: currentDay,
    date: currentDate,
    period: context?.period || "صباحي",
    inspector: context?.inspector || "م/ أحمد وحيد شعبان",
    supervisorRole: "مشرف مكافحة العدوى",
    centerName: context?.centerName || "Waheed IPC",
    generalRecommendation: preset.generalRecommendation,
    observations: preset.observations.map((obs, idx) => ({
      id: `ro-${preset.id}-${Date.now()}-${idx + 1}`,
      location: obs.location,
      observation: obs.observation,
      recommendation: obs.recommendation,
      responsible: obs.responsible,
      status: obs.status,
    })),
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };
}
